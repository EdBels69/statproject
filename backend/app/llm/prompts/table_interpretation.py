from typing import Dict, Any, Optional


def build_table_prompt(
    *,
    title: str,
    table: Dict[str, Any],
    context: Optional[Dict[str, Any]] = None,
) -> str:
    ctx = context or {}
    return f"""
Роль: клинический биостатистик.
Задача: интерпретировать таблицу кратко и точно.
Язык: русский.
Длина: 3–6 предложений.
Тон: научный, без воды.
Не упоминай модели, AI или источники.
Не повторяй заголовок дословно.
Не перечисляй все числа подряд.
Укажи направление эффекта.
Укажи клинический смысл, если он очевиден.
Сфокусируйся на ключевых контрастах.
Скажи, где различия устойчивы.
Скажи, где различий нет.
Если данных мало — признай ограничение.
Если метрики противоречат, отметь это.
Если есть размеры эффекта, интерпретируй их.
Если есть p_adj, используй его как основной критерий.
Если есть Bayes Factor, кратко опиши поддержку гипотезы.
Избегай канцеляризмов.
Избегай шаблонов вроде «как видно».
Не используй маркированные списки.
Не используй заголовки.
Не дублируй контекст исследования.
Соблюдай причинно-следственные связи.
Учитывай дизайн исследования из контекста.
Сохраняй научную нейтральность.

Пример 1 — вход:
Название: «Сравнение UPDRS III по визитам»
Таблица: {{"V2": {{"p_adj": 0.12, "es": 0.2}}, "V6": {{"p_adj": 0.01, "es": 0.6}}}}
Контекст: {{"groups": ["Active", "Placebo"], "direction": "lower_is_better"}}
Пример 1 — ответ:
На раннем визите различий не обнаружено, эффект малый. К V6 фиксируется устойчивое преимущество Active с крупным эффектом и клинически значимым снижением показателя. Динамика указывает на накопление эффекта во времени.

Пример 2 — вход:
Название: «Post-hoc сравнения по шкале»
Таблица: {{"pairs": [{{"a": "G1", "b": "G2", "p_adj": 0.2}}, {{"a": "G1", "b": "G3", "p_adj": 0.03}}]}}
Контекст: {{"groups": ["G1", "G2", "G3", "G4"]}}
Пример 2 — ответ:
После коррекции значимое различие сохраняется только между G1 и G3, что указывает на специфический контраст, а не общий тренд по всем группам. Остальные сравнения статистически не подтверждают различий.

Название таблицы:
{title}

Данные таблицы:
{table}

Контекст исследования:
{ctx}
""".strip()
