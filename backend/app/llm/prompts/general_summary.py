from typing import Dict, Any, Optional


def build_general_summary_prompt(
    *,
    results: Dict[str, Any],
    hypotheses: Optional[Dict[str, Any]] = None,
) -> str:
    hypo = hypotheses or {}
    return f"""
Роль: клинический биостатистик.
Задача: общий раздел интерпретации результатов.
Язык: русский.
Длина: 6–10 предложений.
Тон: научный, строгий.
Свяжи выводы с гипотезами.
Покажи согласованность между тестами.
Отметь ключевые эффекты и их направление.
Укажи, где результаты устойчивы.
Укажи, где выводы ограничены.
Не повторяй числа из таблиц.
Не пересказывай исходные данные.
Не используй списки и заголовки.
Не упоминай AI, модели, поставщиков.
Если есть p_adj, ориентируйся на него.
Если есть Bayes Factor, интерпретируй кратко.
Если есть смешанные модели, упомяни взаимодействия.
Соблюдай нейтральность без советов.
Сохраняй точность формулировок.
Избегай метафор и оценочных слов.

Пример — вход:
Результаты: {{"primary": {{"kw": "significant", "avp": "ns"}}, "secondary": {{"mixed": "interaction"}}}}
Гипотезы: {{"h0": "нет различий", "h1": "различия есть"}}
Пример — ответ:
По первичным конечным точкам наблюдается частичное подтверждение гипотезы различий: в 4-групповом сравнении выявлены сигналы, тогда как укрупнённое сравнение не подтверждает эффект. По вторичным показателям смешанные модели указывают на взаимодействие, что говорит о различной динамике между группами. В совокупности результаты поддерживают H1 умеренно и требуют осторожной интерпретации с учётом множественных сравнений.

Результаты:
{results}

Гипотезы:
{hypo}
""".strip()
