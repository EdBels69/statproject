from typing import Dict, Any, Optional


def build_discussion_prompt(
    *,
    context: Dict[str, Any],
    results: Dict[str, Any],
    constraints: Optional[Dict[str, Any]] = None,
) -> str:
    rules = constraints or {}
    return f"""
Роль: клинический биостатистик.
Задача: написать раздел «Обсуждение».
Язык: русский.
Длина: 5–10 абзацев.
Тон: академический.
Не используй списки.
Не используй подзаголовки.
Не упоминай AI, модели, источники.
Сфокусируйся на интерпретации.
Отметь согласованность между тестами.
Укажи, где эффекты устойчивые.
Укажи, где эффекты слабые.
Отрази клиническую значимость.
Укажи, если эффект зависит от визита.
Укажи, если группы расходятся динамически.
Если есть mixed effects, опиши взаимодействие.
Если есть респондеры, свяжи с динамикой.
Если post-hoc незначимы, скажи об этом.
Если есть корректировка p, ориентируйся на неё.
Если есть BF или ES, интерпретируй кратко.
Укажи ограничения дизайна, не перегружая.
Сохраняй нейтральность без рекомендаций.
Не повторяй числа из таблиц.
Не дублируй цели дословно.
Сделай выводы проверяемыми.

Пример — вход:
Контекст: {{"goals": ["сравнить группы"], "hypotheses": ["H0/H1"], "n_patients": 120}}
Результаты: {{"endpoint": "UPDRS", "kw": "significant", "avp": "p_adj<0.05", "mixed": "interaction"}}
Ограничения: {{"length": "short"}}
Пример — ответ:
Результаты по UPDRS показывают согласованные сигналы различий между группами и в укрупнённом сравнении, что в целом поддерживает гипотезу эффективности. Взаимодействие в mixed effects указывает, что динамика улучшений зависит от визита, а не является равномерной во времени. При этом выраженность эффекта варьирует по временным точкам, что ограничивает силу вывода о стабильности эффекта на всех этапах наблюдения.

Контекст:
{context}

Результаты:
{results}

Ограничения:
{rules}
""".strip()
