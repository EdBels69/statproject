from typing import Dict, Any, Optional


def build_conclusions_prompt(
    *,
    context: Dict[str, Any],
    results: Dict[str, Any],
    constraints: Optional[Dict[str, Any]] = None,
) -> str:
    rules = constraints or {}
    return f"""
Роль: клинический биостатистик.
Задача: написать раздел «Выводы».
Язык: русский.
Формат: 8–12 пунктов, каждый с «• ».
Каждый пункт проверяем по данным.
Укажи направление эффекта, где оно есть.
Отрази результаты 4-группового сравнения.
Отрази укрупнённое сравнение, если есть.
Укажи результаты post-hoc, если есть.
Укажи mixed effects, если есть.
Укажи респондеров, если есть.
Включи 2–3 пункта про ограничения.
Не повторяй числа из таблиц.
Не упоминай AI, модели, источники.
Не используй заголовки.
Не используй списки кроме требуемых пунктов.
Не используй слов «однозначно», «доказано».
Сохраняй нейтральность.
Соблюдай научный стиль.

Пример — вход:
Контекст: {{"goals": ["эффективность"], "hypotheses": ["H0/H1"]}}
Результаты: {{"primary": "kw significant", "avp": "ns", "mixed": "interaction", "responders": "trend"}}
Ограничения: {{"notes": ["малые подгруппы"]}}
Пример — ответ:
• В 4-групповом сравнении выявлены различия по части показателей, что частично поддерживает H1.
• В укрупнённом сравнении Active vs Placebo эффект выражен не во всех визитах.
• Post-hoc анализ не выявляет устойчивых различий после коррекции для части конечных точек.
• Mixed effects указывает на взаимодействие «визит×группа», отражая различную динамику.
• Доля респондеров демонстрирует тенденцию к улучшению в активных группах.
• Ограничение: малые подгруппы снижают мощность для редких исходов.
• Ограничение: множественные сравнения повышают риск ложноположительных сигналов.

Контекст:
{context}

Результаты:
{results}

Ограничения:
{rules}
""".strip()
