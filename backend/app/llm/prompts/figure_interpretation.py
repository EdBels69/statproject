from typing import Dict, Any, Optional


def build_figure_prompt(
    *,
    title: str,
    figure_meta: Dict[str, Any],
    context: Optional[Dict[str, Any]] = None,
) -> str:
    ctx = context or {}
    return f"""
Роль: клинический биостатистик.
Задача: написать подпись к рисунку.
Язык: русский.
Длина: 2–4 предложения.
Тон: точный, без украшательств.
Подчеркни основной тренд.
Отметь различия между группами.
Скажи, на каких визитах или точках тренд меняется.
Укажи, если тренд однонаправленный.
Укажи, если тренды расходятся.
Если различий нет, скажи прямо.
Не повторяй название дословно.
Не пересказывай все числа.
Не используй маркированные списки.
Не используй слова «график показывает».
Избегай шаблонов «как видно».
Избегай оценочных эпитетов.
Сохраняй научную нейтральность.
Если есть клиническое направление, упомяни его.
Если контекст противоречивый, отметь это.
Не упоминай AI, модели и источники.

Пример 1 — вход:
Название: «Динамика показателя по визитам»
Метаданные: {{"series": ["Active", "Placebo"], "visits": ["V2", "V3", "V4"], "trend": "down"}}
Контекст: {{"direction": "lower_is_better"}}
Пример 1 — ответ:
Показатель в группе Active снижается последовательно от V2 к V4, тогда как в Placebo выраженного тренда нет. К V4 кривые расходятся, что указывает на клинически благоприятную динамику в Active.

Пример 2 — вход:
Название: «Сравнение распределений на V6»
Метаданные: {{"groups": ["G1", "G2", "G3", "G4"], "overlap": "high"}}
Контекст: {{"note": "post-hoc незначим"}}
Пример 2 — ответ:
Распределения групп на V6 существенно перекрываются, что согласуется с отсутствием значимых post-hoc различий. Выраженного сдвига медиан между группами не наблюдается.

Название рисунка:
{title}

Метаданные рисунка:
{figure_meta}

Контекст исследования:
{ctx}
""".strip()
